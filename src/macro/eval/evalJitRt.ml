(*
	Run-time support for natively compiled eval code (see evalJitNative.ml).

	Code generated by EvalJitNative is compiled by ocamlopt into a .cmxs and loaded with
	Dynlink. It links against the compiler's own eval modules, so it calls exactly the
	functions the closure compiler's emitters call. Where an emitter is more than a line or
	two, its direct-style twin lives here, written to match EvalEmitter step for step: the
	order in which sub-expressions are evaluated, values checked and positions recorded is
	observable (exceptions, stack traces), so it must not drift.
*)

open Globals
open EvalValue
open EvalContext
open EvalHash
open EvalExceptions
open EvalMisc
open EvalField

(* A loaded unit registers one link function per compiled function. A link function takes
   the resolved run-time data of that function (prototypes, field indices, positions...),
   in the order the generator recorded them, and returns the function itself. *)
let units : (string,(Obj.t array -> vfunc) array) Hashtbl.t = Hashtbl.create 0

let register key fl =
	Hashtbl.replace units key fl

(* EvalContext.push_environment for functions the JIT compiled: they have no locals or captures
   arrays, and the JIT is off under the debugger, so without eval-times it comes down to linking a
   new environment; otherwise the general function runs. *)
let[@inline] push_env ctx info =
	if ctx.detail_times || ctx.debug.support_debugger then
		push_environment ctx info
	else begin
		let eval = get_eval ctx in
		let parent = eval.env in
		let env = {
			env_info = info;
			env_leave_pmin = 0;
			env_leave_pmax = 0;
			env_debug = no_debug;
			env_locals = empty_array;
			env_captures = empty_array;
			env_extra_locals = IntMap.empty;
			env_parent = parent;
			env_eval = eval;
			env_stack_depth = (match parent with None -> 1 | Some env -> env.env_stack_depth + 1);
		} in
		eval.env <- Some env;
		env
	end

(* EvalContext.pop_environment; no_debug's timer does nothing. *)
let[@inline] pop_env ctx env =
	let eval = env.env_eval in
	eval.env <- env.env_parent;
	if env.env_debug != no_debug then env.env_debug.timer()

(* try/catch, as EvalEmitter.emit_try. [catches] pairs the hashed type path of each catch
   with its handler, in source order. *)
let try_catch env body catches =
	let ctx = get_ctx() in
	let eval = env.env_eval in
	if ctx.debug.support_debugger then begin
		Array.iter (fun (path,_) -> Hashtbl.add eval.caught_types path true) catches
	end;
	let restore () =
		Array.iter (fun (path,_) -> Hashtbl.remove eval.caught_types path) catches
	in
	try
		let v = handle_stack_overflow eval body in
		restore();
		v
	with RunTimeException(v,_,_) as exc ->
		eval.caught_exception <- vnull;
		restore();
		build_exception_stack ctx env;
		let rec loop () = match eval.env with
			| Some env' when env' != env ->
				pop_environment ctx env';
				loop();
			| _ ->
				()
		in
		loop();
		let rec find i =
			if i >= Array.length catches then raise_notrace exc
			else begin
				let (path,handler) = Array.unsafe_get catches i in
				if path = key_Dynamic || is v path then handler v
				else find (i + 1)
			end
		in
		find 0

(* instance.call() where call is overridden, as EvalEmitter.emit_method_call up to the
   evaluation of the arguments. Returns the function value to call on [vthis]. *)
let method_field vthis name p =
	let proto = EvalEmitter.get_prototype vthis p in
	try proto_field_raise proto name
	with Not_found -> throw_string (Printf.sprintf "Field %s not found on prototype %s" (rev_hash name) (rev_hash proto.ppath)) p

(* An inline cache for [method_field]: the lookup's result depends only on the receiver's
   prototype, whose names and parent never change, so remember which prototype holds the field and
   at which index; the value itself is read from that prototype on every call, as the lookup would.
   One immutable triple, replaced in one write: a thread switch cannot expose half an update. *)
type call_cache = {
	mutable cc : vprototype * vprototype * int;
}

let no_proto = {
	ppath = -1;
	pfields = [||];
	pnames = IntMap.empty;
	pinstance_fields = [||];
	pinstance_names = IntMap.empty;
	pparent = None;
	pkind = PObject;
	pvalue = vnull;
}

let new_call_cache () = { cc = (no_proto,no_proto,0) }

let rec field_holder proto name =
	match IntMap.find_opt name proto.pnames with
	| Some i -> Some (proto,i)
	| None -> match proto.pparent with
		| Some proto -> field_holder proto name
		| None -> None

(* EvalEmitter.get_prototype, without its call to vresolve for the usual receivers. *)
let get_prototype v p = match v with
	| VInstance {iproto = proto} | VPrototype proto -> proto
	| _ -> EvalEmitter.get_prototype v p

let method_field_cached cache vthis name p =
	let proto = get_prototype vthis p in
	let (proto',holder,i) = cache.cc in
	if proto == proto' then
		holder.pfields.(i)
	else match field_holder proto name with
		| Some (holder,i) ->
			cache.cc <- (proto,holder,i);
			holder.pfields.(i)
		| None ->
			throw_string (Printf.sprintf "Field %s not found on prototype %s" (rev_hash name) (rev_hash proto.ppath)) p

(* Inline caches for fields read by name: where EvalField finds a field depends only on the
   prototype, whose field names and parent never change, so a call site remembers where the field
   was for the last prototype it saw; the value is read from the object or prototype every time.
   One immutable pair, replaced in one write. *)
type field_slot =
	| FSObject of int (* index into ofields *)
	| FSInstance of int (* index into ifields *)
	| FSProto of vprototype * int (* on this prototype, an ancestor of the instance's *)
	| FSMissing (* not found: the lookup gives null *)

type field_cache = {
	mutable fc : vprototype * field_slot;
}

let new_field_cache () = { fc = (no_proto,FSMissing) }

(* The field of an object with a prototype, as EvalField.object_field. *)
let object_field_cached cache o proto name =
	let (proto',slot) = cache.fc in
	if proto == proto' then begin match slot with
		| FSObject i -> o.ofields.(i)
		| _ -> vnull
	end else begin match IntMap.find_opt name proto.pinstance_names with
		| Some i -> cache.fc <- (proto,FSObject i); o.ofields.(i)
		| None -> cache.fc <- (proto,FSMissing); vnull
	end

(* EvalField.field. *)
let field_cached cache v name =
	match v with
	| VObject ({oproto = OProto proto} as o) ->
		object_field_cached cache o proto name
	| VInstance {ikind = IBytes _} when name = key_length ->
		field v name
	| VInstance vi ->
		let proto = vi.iproto in
		let (proto',slot) = cache.fc in
		if proto == proto' then begin match slot with
			| FSInstance i -> vi.ifields.(i)
			| FSProto (holder,i) -> holder.pfields.(i)
			| _ -> vnull
		end else begin match IntMap.find_opt name proto.pinstance_names with
			| Some i -> cache.fc <- (proto,FSInstance i); vi.ifields.(i)
			| None ->
				match field_holder proto name with
				| Some (holder,i) -> cache.fc <- (proto,FSProto (holder,i)); holder.pfields.(i)
				| None -> cache.fc <- (proto,FSMissing); vnull
		end
	| _ ->
		field v name

(* EvalField.dynamic_field. *)
let dynamic_field_cached cache v name = match field_cached cache v name with
	| VFunction(f,false) -> vfield_closure v f
	| v -> v

(* anon_field_read, with the cache for objects of another prototype than the static type's. *)
let rec anon_field_read_cached cache v proto i name p =
	match v with
	| VLazy _ ->
		anon_field_read_cached cache (vresolve v) proto i name p
	| VObject o ->
		begin match o.oproto with
		| OProto proto' when proto' == proto -> o.ofields.(i)
		| OProto proto' -> object_field_cached cache o proto' name
		| ODictionary _ -> object_field o name
		end
	| VNull -> throw_string "field access on null" p
	| v -> field v name

(* EvalEmitter.emit_special_super_call after the arguments. *)
let special_super_call fnew vl vthis =
	let vi' = fnew vl in
	begin match vthis,vi' with
		| VInstance vi,VInstance vi' -> vi.ikind <- vi'.ikind
		| _ -> die "" __LOC__
	end;
	vnull

(* EvalEmitter.emit_field_read_write, with the right-hand side as a thunk. *)
let field_read_write v1 p1 name e2 fop prefix =
	match vresolve v1 with
	| VObject o ->
		let vf = object_field o name in
		let v2 = e2 () in
		let v = fop vf v2 in
		set_object_field o name v;
		if prefix then v else vf
	| VInstance vi ->
		let i = get_instance_field_index vi.iproto name null_pos in
		let vf = vi.ifields.(i) in
		let v2 = e2 () in
		let v = fop vf v2 in
		vi.ifields.(i) <- v;
		if prefix then v else vf
	| VPrototype proto ->
		let i = get_proto_field_index proto name in
		let vf = proto.pfields.(i) in
		let v2 = e2 () in
		let v = fop vf v2 in
		proto.pfields.(i) <- v;
		if prefix then v else vf
	| _ ->
		let vf = field v1 name in
		let v2 = e2 () in
		let v = fop vf v2 in
		(try set_field v1 name v with RunTimeException(v,stack,_) -> raise_notrace (RunTimeException(v,stack,p1)));
		if prefix then v else vf

(* EvalEmitter.emit_field_write after both operands. *)
let field_write v1 p1 name v2 =
	(try set_field v1 name v2 with RunTimeException(v,stack,_) -> raise_notrace (RunTimeException(v,stack,p1)));
	v2

(* EvalEmitter.emit_anon_field_write after both operands. *)
let anon_field_write v1 p proto i name v2 =
	begin match vresolve v1 with
		| VObject o ->
			begin match o.oproto with
			| OProto proto' when proto' == proto ->
				o.ofields.(i) <- v2;
			| _ ->
				set_object_field o name v2
			end
		| VNull ->
			throw_string "field access on null" p
		| _ ->
			set_field v1 name v2;
	end;
	v2

(* EvalEmitter.emit_anon_field_read after the object. *)
let anon_field_read v proto i name p =
	match vresolve v with
	| VObject o ->
		begin match o.oproto with
		| OProto proto' when proto' == proto ->
			o.ofields.(i)
		| _ ->
			object_field o name
		end
	| VNull -> throw_string "field access on null" p
	| v -> field v name

(* EvalEmitter.emit_new_vector_int. *)
let new_vector_int i p =
	if i < 0 then exc_string_p "Vector size must be >= 0" p;
	let a = try
		Array.make i vnull
	with Invalid_argument _ ->
		exc_string_p (Printf.sprintf "Not enough memory to allocate Vector of size %i" i) p;
	in
	EvalEncode.encode_vector_instance a

(* EvalEmitter.emit_string_cca / emit_string_cca_unsafe after both operands. *)
let string_cca v1 v2 p =
	let s = EvalDecode.decode_vstring v1 in
	let index = EvalEmitter.decode_int_p v2 p in
	if index < 0 || index >= s.slength then vnull
	else vint (EvalString.char_at s index)

let string_cca_unsafe v1 v2 p =
	let s = EvalDecode.decode_vstring v1 in
	let index = EvalEmitter.decode_int_p v2 p in
	vint (EvalString.char_at s index)

(* EvalEmitter.emit_mk_pos after the operands. *)
let mk_pos file min max =
	EvalEncode.encode_pos { pfile = EvalDecode.decode_string file; pmin = EvalDecode.decode_int min; pmax = EvalDecode.decode_int max }

(* EvalEmitter.emit_safe_cast after the operand. *)
let safe_cast v1 t p =
	match vresolve v1 with
	| VNull -> v1
	| _ -> if not (is v1 t) then throw_string "Class cast error" p else v1

let too_many_arguments () =
	exc_string "Something went wrong"
